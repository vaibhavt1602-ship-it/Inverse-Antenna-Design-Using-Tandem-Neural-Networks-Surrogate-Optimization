"""
CAD & EM Simulator Exporter for Synthesized Antenna Geometries.

Generates:
  1. CST Microwave Studio VBA Macro (*.bas / *.vba)
  2. Ansys HFSS Python Script (PyAEDT / Scripting API)
  3. Manufacturing Specification Sheet (JSON & CSV)
"""

import json
import os
import pandas as pd


def export_cst_macro(geometry, filename="antenna_cst_macro.vba"):
    """
    Generate CST Microwave Studio VBA script to automatically model the synthesized antenna.
    """
    vba_code = f"""' CST Microwave Studio VBA Macro - Auto-Generated by Inverse Antenna Design ML
' Substrate Material: Rogers RT5880 / FR4 (eps_r = 2.2 / 4.4)

Sub Main ()
    Dim sub_w, sub_l, sub_h As Double
    Dim patch_w, patch_l As Double
    Dim feed_w As Double
    Dim slot1_w, slot1_l, slot2_w, slot2_l As Double

    ' === Synthesized Parameters (mm) ===
    sub_w   = {geometry['Sub_W']:.4f}
    sub_l   = {geometry['Sub_L']:.4f}
    sub_h   = {geometry['Sub_H']:.4f}
    patch_w = {geometry['Patch_W']:.4f}
    patch_l = {geometry['Patch_L']:.4f}
    feed_w  = {geometry['Feed_W']:.4f}
    slot1_w = {geometry['Slot1_W']:.4f}
    slot1_l = {geometry['Slot1_L']:.4f}
    slot2_w = {geometry['Slot2_W']:.4f}
    slot2_l = {geometry['Slot2_L']:.4f}

    ' 1. Create Substrate Brick
    With Brick
        .Reset
        .Name "Substrate"
        .Component "Antenna"
        .Material "FR-4 (lossy)"
        .Xrange -sub_w/2, sub_w/2
        .Yrange -sub_l/2, sub_l/2
        .Zrange 0, sub_h
        .Create
    End With

    ' 2. Create Ground Plane
    With Brick
        .Reset
        .Name "Ground"
        .Component "Antenna"
        .Material "Copper (annealed)"
        .Xrange -sub_w/2, sub_w/2
        .Yrange -sub_l/2, sub_l/2
        .Zrange -0.035, 0
        .Create
    End With

    ' 3. Create Microstrip Patch
    With Brick
        .Reset
        .Name "Patch"
        .Component "Antenna"
        .Material "Copper (annealed)"
        .Xrange -patch_w/2, patch_w/2
        .Yrange -patch_l/2, patch_l/2
        .Zrange sub_h, sub_h + 0.035
        .Create
    End With

    ' 4. Create Microstrip Feed Line
    With Brick
        .Reset
        .Name "FeedLine"
        .Component "Antenna"
        .Material "Copper (annealed)"
        .Xrange -feed_w/2, feed_w/2
        .Yrange -sub_l/2, -patch_l/2
        .Zrange sub_h, sub_h + 0.035
        .Create
    End With

    ' 5. Cut Slot 1
    With Brick
        .Reset
        .Name "Slot1"
        .Component "Antenna"
        .Material "Nickel"
        .Xrange -slot1_w/2, slot1_w/2
        .Yrange 0, slot1_l
        .Zrange sub_h - 0.01, sub_h + 0.05
        .Create
    End With
    Solid.Subtract "Antenna:Patch", "Antenna:Slot1"

    ' 6. Cut Slot 2
    With Brick
        .Reset
        .Name "Slot2"
        .Component "Antenna"
        .Material "Nickel"
        .Xrange -slot2_w/2, slot2_w/2
        .Yrange -slot2_l, 0
        .Zrange sub_h - 0.01, sub_h + 0.05
        .Create
    End With
    Solid.Subtract "Antenna:Patch", "Antenna:Slot2"

    ' Combine Feed and Patch
    Solid.Add "Antenna:Patch", "Antenna:FeedLine"

    MsgBox "Antenna Geometry Successfully Built in CST!", vbInformation, "Inverse Antenna Design"
End Sub
"""
    with open(filename, "w", encoding="utf-8") as f:
        f.write(vba_code)
    return filename


def export_hfss_script(geometry, filename="antenna_hfss_script.py"):
    """
    Generate Ansys HFSS Python (PyAEDT) script to model the antenna in HFSS.
    """
    py_code = f"""# Ansys HFSS Automation Script (PyAEDT)
# Auto-generated by Inverse Antenna Design ML Project

from pyaedt import Hfss

# Initialize HFSS Session
hfss = Hfss(specified_version="2024.1", non_graphical=False, new_desktop_session=True)
hfss.modeler.model_units = "mm"

# Dimensions (mm)
sub_w   = {geometry['Sub_W']:.4f}
sub_l   = {geometry['Sub_L']:.4f}
sub_h   = {geometry['Sub_H']:.4f}
patch_w = {geometry['Patch_W']:.4f}
patch_l = {geometry['Patch_L']:.4f}
feed_w  = {geometry['Feed_W']:.4f}
slot1_w = {geometry['Slot1_W']:.4f}
slot1_l = {geometry['Slot1_L']:.4f}
slot2_w = {geometry['Slot2_W']:.4f}
slot2_l = {geometry['Slot2_L']:.4f}

# 1. Create Substrate
substrate = hfss.modeler.create_box(
    position=[-sub_w/2, -sub_l/2, 0],
    dimensions_list=[sub_w, sub_l, sub_h],
    name="Substrate",
    matname="FR4_epoxy"
)

# 2. Create Ground Plane
ground = hfss.modeler.create_rectangle(
    origin=[-sub_w/2, -sub_l/2, 0],
    sizes=[sub_w, sub_l],
    name="GroundPlane",
    which_plane="XY"
)
hfss.assign_perfecte_to_sheets(ground, "Ground_PE")

# 3. Create Patch
patch = hfss.modeler.create_rectangle(
    origin=[-patch_w/2, -patch_l/2, sub_h],
    sizes=[patch_w, patch_l],
    name="Patch",
    which_plane="XY"
)

# 4. Create Feed Line
feed = hfss.modeler.create_rectangle(
    origin=[-feed_w/2, -sub_l/2, sub_h],
    sizes=[feed_w, (sub_l - patch_l)/2],
    name="FeedLine",
    which_plane="XY"
)

# Unite Patch and Feed
patch.unite(feed)
hfss.assign_perfecte_to_sheets(patch, "Patch_PE")

print("Antenna created successfully in Ansys HFSS!")
"""
    with open(filename, "w", encoding="utf-8") as f:
        f.write(py_code)
    return filename


def export_specification_sheet(geometry, performance, filename_prefix="antenna_specs"):
    """Save parameters to JSON and CSV."""
    data = {
        "Geometry_Parameters_mm": geometry,
        "Simulated_Performance": performance
    }
    json_path = f"{filename_prefix}.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=4)

    # Flatten for CSV
    flat_data = {f"geom_{k}_mm": [v] for k, v in geometry.items()}
    flat_data.update({f"perf_{k}": [v] for k, v in performance.items()})
    csv_path = f"{filename_prefix}.csv"
    pd.DataFrame(flat_data).to_csv(csv_path, index=False)

    return json_path, csv_path
